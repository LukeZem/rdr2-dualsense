"""Generate mod/src/item_states.inc: the game's item-interaction states (TASK_ITEM_INTERACTION,
femga/rdr3_discoveries tasks/TASK_ITEM_INTERACTION/readme.md section 4) that mean eating, drinking,
smoking or cleaning a gun. GET_ITEM_INTERACTION_STATE returns these hashes."""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "third_party" / "downloads" / "research_events" / "rdr3_discoveries" / "tasks" / "TASK_ITEM_INTERACTION" / "readme.md"
OUT = REPO / "mod" / "src" / "item_states.inc"


def kind(name: str) -> str:
    if "CARD" in name or "INSPECT" in name:
        return ""
    if "CLEAN" in name:
        return "clean"
    if any(w in name for w in ("CIGAR", "PIPE", "SMOKE")):
        return "smoke"
    if any(w in name for w in ("DRINK", "BOTTLE", "COFFEE", "TONIC", "FLASK", "CHUG", "SIP")):
        return "drink"
    if any(w in name for w in ("EAT_", "STEW", "CANNED", "BITE", "CHEW")):
        return "eat"
    return ""


def main():
    text = SRC.read_text(encoding="utf-8")
    rows = re.findall(r"\|\s*[^|]*\|\s*([A-Z0-9@_\-\.]+)\s*\|\s*(0x[0-9A-Fa-f]{8})\s*\|", text)
    seen = {}
    for name, h in rows:
        k = kind(name)
        if k:
            seen[int(h, 16)] = (k, name)
    lines = [f"// generated by tools/dev/gen_item_states.py from {SRC.relative_to(REPO).as_posix()} - do not edit",
             "// {state hash, kind}: eat, drink, smoke, clean"]
    for h, (k, name) in sorted(seen.items()):
        lines.append(f'{{0x{h:08X}u, "{k}"}},  // {name}')
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    counts = {}
    for k, _ in seen.values():
        counts[k] = counts.get(k, 0) + 1
    print(f"{len(seen)} states -> {OUT}: {counts}")


if __name__ == "__main__":
    sys.exit(main())
